        "    RANK() OVER (PARTITION BY r.city ORDER BY r.no_show_pct DESC) AS rank_in_city,\n",
        "    CASE\n",
        "        WHEN r.no_show_pct > o.overall_pct THEN 'above'\n",
        "        WHEN r.no_show_pct < o.overall_pct THEN 'below'\n",
        "        ELSE 'equal'\n",
        "    END AS vs_overall\n",
        "FROM clinic_rates r\n",
        "CROSS JOIN overall o\n",
        "ORDER BY r.city, rank_in_city;"
