        "-- Task 2.4 — Month-by-month trend\n",
        "-- ==========================================\n",
        "WITH monthly AS (\n",
        "    SELECT\n",
        "        SUBSTR(appt_date, 1, 7) AS month,\n",
        "        COUNT(*) AS appointments,\n",
        "        ROUND(100.0 * SUM(no_show) / COUNT(*), 1) AS no_show_pct\n",
        "    FROM appointments\n",
        "    GROUP BY month\n",
        ")\n",
        "SELECT\n",
        "    month,\n",
        "    appointments,\n",
        "    no_show_pct,\n",
        "    ROUND(no_show_pct - LAG(no_show_pct, 1) OVER (ORDER BY month), 1) AS rate_change\n",
        "FROM monthly\n",
        "ORDER BY month;\n",
